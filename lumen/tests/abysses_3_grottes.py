"""Acte IV — les Grottes Miroirs : salle des Écumes, clé, porte, salle des Marées (vannes + orbe), arène et boss."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from qa_lib import QA

q = QA("abysses-grottes")
q.load("&ile=abysses")
q.js("arrivée", "T.arrive()", "play")
q.js("parler à Marée", "(async()=>{ __lumen.tpZone('greve'); await T.tick(200); return await T.talkTo('maree') })()")
q.js("lac résolu (API)", "(()=>{ ['la1','la2','la3'].forEach(g=>T.solve(g)); return T.q('q_abysses')+' / '+T.q('q_grottes') })()", "done")
q.js("entrée des Grottes", "(async()=>{ __lumen.tpZone('grottes'); await T.tick(500); return T.q('q_grottes') })()", "active:combat")
q.js("audit de ciblage (salle des Marées)", "(async()=>{ return await T.auditDevices('grottes') })()", lambda r: '"ko":[]' in r)
q.js("la salle des Écumes est gardée", "__lumen.combat.enemies.filter(e=>e.room==='gr_combat'&&e.state!=='dead').length", lambda r: r >= 5)
q.js("combat de la salle des Écumes", "(async()=>{ const L=__lumen; L.tpZone('grottes',[27,6]); await T.tick(300); const k=await T.cutAndKill(x=>x.room==='gr_combat', 90000); await T.tick(1500); return k+' tués, sceau='+L.isl.gates.gr_combat.open })()", "sceau=true")
q.js("étape clé", "T.q('q_grottes')", "active:cle")
q.js("coffre de la clé", "T.openChest('ch_cle_g')", "ouvert:true")
q.js("clé en poche", "__lumen.st.inv.cle_grottes||0", lambda r: r == 1)
q.js("porte de corail (ciblage réel depuis le hall)", "(async()=>{ const L=__lumen; const z=L.G.zones.find(z=>z.id==='grottes'); L.tpZone('grottes',[15,8]); await T.tick(300); return await T.useTarget('lock', (z.ox+15)*2, (z.oy+9)*2) })()")
q.js("porte ouverte", "[__lumen.isl.gates.gr_key.open, __lumen.st.inv.cle_grottes||0].join()", "true,0")
q.js("salle des Marées : résolution par interactions", "(async()=>{ __lumen.tpZone('grottes',[15,14]); await T.tick(300); return await T.realSolve('gr_eau') })()", lambda r: '"open":true' in r)
q.js("barrière ouverte", "__lumen.isl.gates.gr_eau.open", lambda r: r is True)
q.js("arène : boss présent", "(async()=>{ const L=__lumen; L.tpZone('grottes',[16,29]); await T.tick(800); const b=L.combat.enemies.find(e=>e.boss); return b?b.type+':'+b.hp:'aucun' })()", "gardien_marees")
q.js("combat du boss", "(async()=>{ T.heal(); return await T.fightBoss(120000) })()", "dead\":true")
q.js("sceau de l'arène", "(async()=>{ await T.tick(3000); const L=__lumen; return [L.isl.gates.gr_arene.open, L.st.flags.boss_marees].join() })()", "true,1")
q.js("cristal des Grottes éveillé", "!!__lumen.st.world.warps.grottes", lambda r: r is True)
q.js("coffre de la perle (après le boss)", "T.openChest('ch_perle_g')", "ouvert:true")
q.js("quête : retour à Marée", "T.q('q_grottes')", "active:retour")
q.js("quête : récompenses", "(async()=>{ const L=__lumen; const b=T.pre(); L.tpZone('greve'); await T.tick(300); await T.talkTo('maree'); return await T.rewardCheck('q_grottes', b) })()", "récompenses ok")
q.js("Phare lancé", "T.q('q_phare_abysses')", "active:phare")
q.js("secrets : cachette des Grottes", "(async()=>{ const L=__lumen; const c=L.world.chestViews['ch_cache_g']; return c? 'présent':'absent' })()", "présent")
q.done()
